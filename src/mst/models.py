"""Dependency-free data model for traceable multimodal lessons.

The public model intentionally uses plain dataclasses.  A lesson map is a
portable interchange document rather than an ORM record, so callers can
construct it in Python, serialise it to JSON, or pass a decoded JSON mapping
to :func:`LessonMap.from_dict` without installing a validation framework.

The names in this module follow the lesson-reconstruction contract.  A few
legacy aliases (``pages``, ``audio_segments`` and ``exam_evidence_level``)
are accepted so maps generated by earlier experiments remain readable.
"""

