@dataclass
class LessonMap(ModelMixin):
    """Portable root object joining visual, speech, knowledge and review data."""

    schema_version: str = "1.0"
    map_kind: str = "lesson-reconstruction"
    subject: str = "generic"
    profile: str = "generic"
    lesson_id: str | None = None
    chapter_id: str | None = None
    title: str | None = None
    theme: str | None = None
    source: dict[str, Any] = field(default_factory=dict)
    sources: list[SourceAsset] = field(default_factory=list)
    source_assets: list[SourceAsset] = field(default_factory=list)
    pages: list[VisualFrame] = field(default_factory=list)
    visual_sources: list[VisualFrame] = field(default_factory=list)
    speech_segments: list[SpeechSegment] = field(default_factory=list)
    media_segments: list[SpeechSegment] = field(default_factory=list)
    audio_segments: list[SpeechSegment] = field(default_factory=list)
    alignments: list[Alignment] = field(default_factory=list)
    units: list[KnowledgeUnit] = field(default_factory=list)
    claims: list[Claim] = field(default_factory=list)
    claim_ledger: list[Claim] = field(default_factory=list)
    review_items: list[ReviewItem] = field(default_factory=list)
    lessons: list[Lesson] = field(default_factory=list)
    assessment_evidence: list[Evidence] = field(default_factory=list)
    chapter_index: list[dict[str, Any]] = field(default_factory=list)
    notes: dict[str, Any] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        self.sources = [SourceAsset.from_dict(item) for item in _merge_records(self.sources, self.source_assets, "source_id")]
        self.source_assets = list(self.sources)
        self.pages = [VisualFrame.from_dict(item) for item in _merge_records(self.pages, self.visual_sources, "visual_id")]
        self.visual_sources = list(self.pages)
        self.speech_segments = [SpeechSegment.from_dict(item) for item in _merge_records(self.speech_segments, [*self.media_segments, *self.audio_segments], "segment_id")]
        self.media_segments = list(self.speech_segments)
        self.audio_segments = list(self.speech_segments)
        self.alignments = [Alignment.from_dict(item) for item in _list(self.alignments) if Alignment.from_dict(item) is not None]
        self.units = [KnowledgeUnit.from_dict(item) for item in _list(self.units)]
        self.claims = [Claim.from_dict(item) for item in _merge_records(self.claims, self.claim_ledger, "claim_id")]
        self.claim_ledger = list(self.claims)
        self.review_items = [ReviewItem.from_dict(item) for item in _list(self.review_items)]
        self.lessons = [Lesson.from_dict(item) for item in _list(self.lessons)]
        self.assessment_evidence = [Evidence.from_dict(item) for item in _list(self.assessment_evidence)]

    @property
    def visual_frames(self) -> list[VisualFrame]:
        return self.pages

    @property
    def media(self) -> list[SpeechSegment]:
        return self.speech_segments

    @classmethod
    def from_dict(cls, value: Mapping[str, Any] | "LessonMap") -> "LessonMap":
        if isinstance(value, cls):
            return value
        data = dict(value)
        raw_sources = _first(data, "sources", "source_assets", default=[])
        # A legacy root ``source`` object is metadata, not a source asset.
        if isinstance(raw_sources, Mapping):
            raw_sources = []
        raw_pages = _first(data, "pages", "visual_sources", default=[])
        raw_visual_alias = data.get("visual_sources", []) if "pages" in data else []
        raw_segments = _first(data, "speech_segments", "media_segments", "audio_segments", default=[])
        aliases: list[Any] = []
        if "media_segments" in data:
            aliases.extend(_records(data.get("media_segments"), "segment_id"))
        if "audio_segments" in data:
            aliases.extend(_records(data.get("audio_segments"), "segment_id"))
        return cls(
            schema_version=str(_first(data, "schema_version", "version", default="1.0")),
            map_kind=str(_first(data, "map_kind", "kind", default="lesson-reconstruction")),
            subject=str(_first(data, "subject", default="generic")),
            profile=str(_first(data, "profile", default="generic")),
            lesson_id=_first(data, "lesson_id"),
            chapter_id=_first(data, "chapter_id"),
            title=_first(data, "title", "name"),
            theme=_first(data, "theme"),
            source=dict(_first(data, "source", default={}) or {}) if isinstance(_first(data, "source", default={}), Mapping) else {},
            sources=[SourceAsset.from_dict(item) for item in _records(raw_sources, "source_id")],
            source_assets=[SourceAsset.from_dict(item) for item in _records(data.get("source_assets", []), "source_id")],
            pages=[VisualFrame.from_dict(item) for item in _records(raw_pages, "visual_id")],
            visual_sources=[VisualFrame.from_dict(item) for item in _records(raw_visual_alias, "visual_id")],
            speech_segments=[SpeechSegment.from_dict(item) for item in _records(raw_segments, "segment_id")],
            media_segments=[SpeechSegment.from_dict(item) for item in aliases],
            audio_segments=[],
            alignments=[Alignment.from_dict(item) for item in _records(data.get("alignments", []), "alignment_id")],
            units=[KnowledgeUnit.from_dict(item) for item in _records(data.get("units", []), "unit_id")],
            claims=[Claim.from_dict(item) for item in _records(_first(data, "claims", "claim_ledger", "claimLedger", default=[]), "claim_id")],
            claim_ledger=[Claim.from_dict(item) for item in _records(data.get("claim_ledger", []), "claim_id")],
            review_items=[ReviewItem.from_dict(item) for item in _records(data.get("review_items", data.get("reviews", [])), "review_id")],
            lessons=[Lesson.from_dict(item) for item in _records(data.get("lessons", []), "lesson_id")],
            assessment_evidence=[Evidence.from_dict(item) for item in _records(data.get("assessment_evidence", []), "evidence_id")],
            chapter_index=[dict(item) if isinstance(item, Mapping) else {"value": item} for item in _list(data.get("chapter_index", []))],
            notes=dict(_first(data, "notes", default={}) or {}) if isinstance(_first(data, "notes", default={}), Mapping) else {"text": data.get("notes")},
            metadata=dict(_first(data, "metadata", default={}) or {}),
        )

    @classmethod
    def from_json(cls, value: str | Path) -> "LessonMap":
        path_or_text = str(value)
        if path_or_text.lstrip().startswith("{"):
            return cls.from_dict(json.loads(path_or_text))
        return cls.from_dict(json.loads(Path(path_or_text).read_text(encoding="utf-8")))

    def write_json(self, path: str | Path, *, indent: int = 2, ensure_ascii: bool = False) -> Path:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(self.to_json(indent=indent, ensure_ascii=ensure_ascii) + "\n", encoding="utf-8")
        return target


def coerce_lesson_map(value: LessonMap | Mapping[str, Any] | str | Path) -> LessonMap:
    """Return a :class:`LessonMap` from an object, mapping, or JSON path."""

    if isinstance(value, LessonMap):
        return value
    if isinstance(value, (str, Path)):
        return LessonMap.from_json(value)
    return LessonMap.from_dict(value)


