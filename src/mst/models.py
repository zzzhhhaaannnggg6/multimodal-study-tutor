def _enum_value(value: Any) -> Any:
    return value.value if isinstance(value, Enum) else value


def _jsonable(value: Any) -> Any:
    """Convert nested dataclasses/enums to JSON-compatible values."""

    if isinstance(value, Enum):
        return value.value
    if is_dataclass(value):
        return {
            item.name: _jsonable(getattr(value, item.name))
            for item in fields(value)
            if getattr(value, item.name) is not None
        }
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(item) for item in value]
    return value


def _as_mapping(value: Any) -> dict[str, Any]:
    if isinstance(value, Mapping):
        return dict(value)
    if is_dataclass(value):
        return {item.name: getattr(value, item.name) for item in fields(value)}
    raise TypeError(f"expected a mapping or dataclass, got {type(value).__name__}")


def _list(value: Any) -> list[Any]:
    if value is None:
        return []
    if isinstance(value, list):
        return value
    if isinstance(value, tuple):
        return list(value)
    return [value]


def _records(value: Any, id_key: str) -> list[Any]:
    """Accept both JSON arrays and ID-keyed record objects."""

    if isinstance(value, Mapping):
        rows: list[Any] = []
        for key, item in value.items():
            if isinstance(item, Mapping):
                row = dict(item)
                row.setdefault(id_key, str(key))
                rows.append(row)
            else:
                rows.append(item)
        return rows
    return _list(value)


def _first(mapping: Mapping[str, Any], *keys: str, default: Any = None) -> Any:
    for key in keys:
        if key in mapping and mapping[key] is not None:
            return mapping[key]
    return default


def _merge_records(primary: Sequence[Any], aliases: Sequence[Any], key: str) -> list[Any]:
    """Merge canonical and legacy arrays while avoiding alias duplicates."""

    result: list[Any] = []
    seen: set[str] = set()
    for item in [*primary, *aliases]:
        if isinstance(item, Mapping):
            ident = item.get(key) or item.get("id") or item.get("page_id")
        else:
            ident = getattr(item, key, None) or getattr(item, "id", None)
        marker = str(ident) if ident is not None else ""
        if marker and marker in seen:
            continue
        if marker:
            seen.add(marker)
        result.append(item)
    return result


class ModelMixin:
    """Small common API shared by all records."""

    _json_name: ClassVar[str | None] = None

    def to_dict(self) -> dict[str, Any]:
        return _jsonable(self)

    # Familiar aliases make the dependency-free dataclasses easy to swap into
    # code that otherwise uses Pydantic models.
    def model_dump(self) -> dict[str, Any]:
        return self.to_dict()

    def dict(self) -> dict[str, Any]:
        return self.to_dict()

    def to_json(self, *, indent: int = 2, ensure_ascii: bool = False) -> str:
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=ensure_ascii)

    def json(self, *, indent: int = 2, ensure_ascii: bool = False) -> str:
        return self.to_json(indent=indent, ensure_ascii=ensure_ascii)


