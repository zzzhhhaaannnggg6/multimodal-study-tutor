        status = str(_first(data, "status", default="verified" if verified else "pending"))
        return cls(
            evidence_id=_first(data, "evidence_id", "id"),
            kind=str(_first(data, "kind", "source_kind", "source_type", "type", default="material")),
            ref=_first(data, "ref", "reference", "source_ref", "document_ref"),
            source_id=_first(data, "source_id"),
            quote=_first(data, "quote", "excerpt", "text"),
            excerpt=_first(data, "excerpt"),
            page=_first(data, "page", "page_number"),
            section=_first(data, "section", "paragraph", "segment"),
            start=_first(data, "start", "start_time", "start_seconds"),
            end=_first(data, "end", "end_time", "end_seconds"),
            timestamp=_first(data, "timestamp", "time"),
            locator=_first(data, "locator", "location"),
            document=_first(data, "document", "file"),
            verified=verified,
            status=status,
            note=_first(data, "note", "notes"),
            metadata=dict(_first(data, "metadata", default={}) or {}),
        )


